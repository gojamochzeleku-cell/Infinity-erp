import os
import io
import base64
import requests
from django.http import HttpResponse
from django.contrib.auth.decorators import login_required
from django.shortcuts import get_object_or_404
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import A4
from reportlab.lib.colors import HexColor
from reportlab.lib.utils import ImageReader
from .models import Tender

@login_required
def generate_cover_sheet(request, pk):
    company = getattr(request, 'company', None)
    tender = get_object_or_404(Tender, pk=pk, company=company)

    # Create the PDF in memory
    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=A4)
    W, H = A4

    # Colors
    gold = HexColor('#d4af37')
    black = HexColor('#111111')
    grey = HexColor('#555555')
    light_grey = HexColor('#f4f4f4')

    # --- HEADER ---
    c.setFillColor(black)
    c.setFont("Helvetica-Bold", 24)
    c.drawCentredString(W/2, H - 50, "INFINITY INVESTMENT INSTITUTE")
    
    c.setFont("Helvetica", 12)
    c.setFillColor(grey)
    c.drawCentredString(W/2, H - 70, "Tender & Import Management")
    
    # Gold Line
    c.setStrokeColor(gold)
    c.setLineWidth(3)
    c.line(50, H - 80, W - 50, H - 80)
    c.setStrokeColor(black)
    c.setLineWidth(1)

    # --- TITLE ---
    c.setFillColor(black)
    c.setFont("Helvetica-Bold", 18)
    c.drawCentredString(W/2, H - 110, "BID SUBMISSION COVER SHEET")

    # --- TENDER DETAILS ---
    c.setFont("Helvetica-Bold", 11)
    c.setFillColor(black)
    
    y = H - 150
    c.drawString(50, y, "Tender Reference Number:")
    c.setFont("Helvetica", 11)
    c.drawString(220, y, tender.bid_reference_number)
    
    y -= 25
    c.setFont("Helvetica-Bold", 11)
    c.drawString(50, y, "Purchaser Organization:")
    c.setFont("Helvetica", 11)
    c.drawString(220, y, tender.purchaser_name)
    
    y -= 25
    c.setFont("Helvetica-Bold", 11)
    c.drawString(50, y, "Bid Title:")
    c.setFont("Helvetica", 11)
    # Split title if it's too long
    title_text = tender.bid_title
    if len(title_text) > 60:
        c.drawString(220, y, title_text[:60])
        c.drawString(220, y - 15, title_text[60:])
        y -= 15
    else:
        c.drawString(220, y, title_text)
    
    y -= 25
    c.setFont("Helvetica-Bold", 11)
    c.drawString(50, y, "Submission Date:")
    c.setFont("Helvetica", 11)
    c.drawString(220, y, tender.bid_submission_date.strftime('%B %d, %Y') if tender.bid_submission_date else "N/A")

    y -= 25
    c.setFont("Helvetica-Bold", 11)
    c.drawString(50, y, "Tender Serial Number:")
    c.setFont("Helvetica", 11)
    c.drawString(220, y, tender.serial_number)

    y -= 25
    c.setFont("Helvetica-Bold", 11)
    c.drawString(50, y, "CPO Amount:")
    c.setFont("Helvetica", 11)
    c.drawString(220, y, f"{tender.cpo_amount} ETB ({tender.get_cpo_type_display()})")

    # --- FINANCIAL DETAILS BOX ---
    y -= 50
    c.setFillColor(light_grey)
    c.rect(50, y - 60, W - 100, 60, fill=1, stroke=0)
    
    c.setFillColor(black)
    c.setFont("Helvetica-Bold", 12)
    c.drawString(60, y - 20, "TOTAL BID PRICE:")
    
    c.setFont("Helvetica-Bold", 18)
    if tender.final_price > 0:
        c.drawString(60, y - 45, f"{tender.final_price:,.2f} ETB")
    else:
        c.drawString(60, y - 45, "PENDING CEO APPROVAL")

    # --- SIGNATURES & QR ---
    y -= 120
    c.setFont("Helvetica-Bold", 11)
    c.drawString(50, y, "Bid Manager Signature:")
    c.drawString(50, y - 60, "_______________________________")
    
    c.drawString(W/2 + 20, y, "CEO / Authorized Signature:")
    
    # Draw CEO Signature if it exists
    if tender.ceo_signature:
        try:
            # Decode base64 signature
            sig_data = tender.ceo_signature.split(",")[1]
            img_data = base64.b64decode(sig_data)
            img = ImageReader(io.BytesIO(img_data))
            c.drawImage(img, W/2 + 20, y - 55, width=150, height=50, preserveAspectRatio=True)
        except Exception as e:
            pass # Ignore if image fails
            
    c.drawString(W/2 + 20, y - 60, "_______________________________")

    # QR Code (Bottom Right)
    try:
        qr_url = f"https://api.qrserver.com/v1/create-qr-code/?size=150x150&data={tender.serial_number}"
        qr_response = requests.get(qr_url, timeout=10)
        qr_img = ImageReader(io.BytesIO(qr_response.content))
        c.drawImage(qr_img, W - 150, 50, width=100, height=100)
    except Exception as e:
        c.drawString(W - 150, 100, "[QR Code Error]")

    c.setFont("Helvetica", 8)
    c.drawString(50, 50, "Generated by Infinity Investment Institute ERP")

    c.showPage()
    c.save()
    buffer.seek(0)

    # Return as downloadable PDF
    response = HttpResponse(buffer, content_type='application/pdf')
    response['Content-Disposition'] = f'attachment; filename="Cover_Sheet_{tender.serial_number}.pdf"'
    return response
